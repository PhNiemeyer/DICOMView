export const dictionaries: Record<Lang, Record<DictKey, string>> = { de, en };

let current: Lang = 'de';
export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
}
export function getLang() {
  return current;
}

export function t(key: DictKey, vars?: Record<string, string | number>): string {
  let s = dictionaries[current][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function fmtNum(n: number, digits = 1) {
  return n.toLocaleString(current === 'de' ? 'de-DE' : 'en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits });
}

export function fmtDicomDate(d: string) {
  if (!/^\d{8}$/.test(d)) return '';
  const dt = new Date(+d.slice(0, 4), +d.slice(4, 6) - 1, +d.slice(6, 8));
  return dt.toLocaleDateString(current === 'de' ? 'de-DE' : 'en-GB', { day: '2-digit', month: '2-digit', year: 'numeric' });
}
